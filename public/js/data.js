    const seen = new Set();
    const key = s => s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');
    const out = [];
    for (const s of list) {
      const [c, ...rest] = s.split('|');
      if (seen.has(key(c))) continue;
      seen.add(key(c));
      const a = rest.filter(x => !seen.has(key(x)) && seen.add(key(x)));
      out.push(a.length ? { c, a } : { c });
    }
    return out;
